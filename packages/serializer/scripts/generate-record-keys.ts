// Writes src/protocol-record-keys.ts, the field names of every templated record list, from the
// protocol types in src/protocol.ts and src/value.ts. Run after changing those types:
//   node packages/serializer/scripts/generate-record-keys.ts
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type * as TS from 'typescript';
import { PROTOCOL_TEMPLATED_LISTS } from '../src/protocol-templated-lists.ts';

const ts = createRequire(import.meta.url)('typescript') as typeof TS;
const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const protocolFile = resolve(packageDirectory, 'src/protocol.ts');
const valueFile = resolve(packageDirectory, 'src/value.ts');
export const RECORD_KEYS_FILE = resolve(packageDirectory, 'src/protocol-record-keys.ts');

// Fields typed `unknown` that carry a serialized graph value envelope; only state records hold one.
const ENVELOPE_FIELDS = new Set(['value', 'key', 'error']);
const PAYLOAD_TYPES = {
	'markless/state': 'ProtocolStatePayload',
	'markless/view': 'ProtocolViewPayload',
} as const;

export function generateRecordKeysSource(): string {
	const program = ts.createProgram([protocolFile, valueFile], {
		strict: true,
		noEmit: true,
		allowImportingTsExtensions: true,
		target: ts.ScriptTarget.ES2022,
		module: ts.ModuleKind.ESNext,
		moduleResolution: ts.ModuleResolutionKind.Bundler,
	});
	const checker = program.getTypeChecker();
	const aliasType = (file: string, name: string) => {
		const source = program.getSourceFile(file)!;
		const alias = source.statements.find(
			(statement): statement is TS.TypeAliasDeclaration =>
				ts.isTypeAliasDeclaration(statement) && statement.name.text === name,
		);
		if (!alias) throw new Error(`MARKLESS_RECORD_KEYS_TYPE_MISSING: ${name}`);
		return checker.getTypeAtLocation(alias.name);
	};
	const envelopeType = aliasType(valueFile, 'SerializedGraphPayload');

	const collect = (type: TS.Type, keys: string[], seen: Set<TS.Type>, envelopes: boolean) => {
		if (seen.has(type)) return;
		seen.add(type);
		if (type.isUnion() || type.isIntersection()) {
			for (const member of type.types) collect(member, keys, seen, envelopes);
			return;
		}
		if (checker.isArrayType(type) || checker.isTupleType(type)) {
			for (const element of checker.getTypeArguments(type as TS.TypeReference))
				collect(element, keys, seen, envelopes);
			return;
		}
		if (!(type.flags & ts.TypeFlags.Object) || type.getCallSignatures().length > 0) return;
		for (const property of checker.getPropertiesOfType(type)) {
			const name = property.getName();
			if (/\d/.test(name)) throw new Error(`MARKLESS_RECORD_KEYS_DIGIT: ${name}`);
			if (!keys.includes(name)) keys.push(name);
			const propertyType = checker.getTypeOfSymbol(property);
			if (propertyType.flags & ts.TypeFlags.Unknown) {
				if (envelopes && ENVELOPE_FIELDS.has(name))
					collect(envelopeType, keys, seen, envelopes);
				continue;
			}
			collect(propertyType, keys, seen, envelopes);
		}
	};

	const tables: string[] = [];
	for (const [payloadType, aliasName] of Object.entries(PAYLOAD_TYPES)) {
		const payload = aliasType(protocolFile, aliasName);
		const lines: string[] = [];
		for (const list of PROTOCOL_TEMPLATED_LISTS[payloadType as keyof typeof PAYLOAD_TYPES]) {
			const property = payload.getProperty(list);
			if (!property) throw new Error(`MARKLESS_RECORD_KEYS_LIST_MISSING: ${aliasName}.${list}`);
			const keys: string[] = [];
			collect(
				checker.getNonNullableType(checker.getTypeOfSymbol(property)),
				keys,
				new Set(),
				payloadType === 'markless/state',
			);
			lines.push(`\t\t${list}: '${keys.join(' ')}',`);
		}
		tables.push(`\t'${payloadType}': {\n${lines.join('\n')}\n\t},`);
	}
	return [
		'// Generated by packages/serializer/scripts/generate-record-keys.ts from protocol.ts and value.ts; do not edit.',
		'/** The field names each templated record list may spell, in the order its templates index them. */',
		'export const PROTOCOL_RECORD_KEYS = {',
		...tables,
		'} as const;',
		'',
	].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(RECORD_KEYS_FILE, generateRecordKeysSource());
	console.log(`wrote ${RECORD_KEYS_FILE}`);
}
