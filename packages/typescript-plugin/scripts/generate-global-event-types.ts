// Writes the DOM event types an element may listen for on the document (`onDocumentKeyDown`) and on
// the window (`onWindowResize`): the keys of TypeScript's DocumentEventMap and WindowEventMap, less
// the events that never reach that target. The compiler refuses any other name; the d.ts types the
// same set. Run after upgrading TypeScript:
//   node packages/typescript-plugin/scripts/generate-global-event-types.ts
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const GLOBAL_EVENT_TYPES_DTS_FILE = resolve(
	packageDirectory,
	'src/global-event-types.generated.d.ts',
);
export const GLOBAL_EVENT_TYPES_COMPILER_FILE = resolve(
	packageDirectory,
	'../compiler/src/ast/global-event-types.generated.ts',
);

/** Fired at an element without bubbling, so no document or window listener in the bubble phase ever sees one. */
const ELEMENT_ONLY_EVENTS = [
	'abort',
	'beforetoggle',
	'cancel',
	'canplay',
	'canplaythrough',
	'close',
	'contextlost',
	'contextrestored',
	'cuechange',
	'durationchange',
	'emptied',
	'encrypted',
	'ended',
	'formdata',
	'invalid',
	'loadeddata',
	'loadedmetadata',
	'loadstart',
	'mouseenter',
	'mouseleave',
	'pause',
	'play',
	'playing',
	'pointerenter',
	'pointerleave',
	'progress',
	'ratechange',
	'seeked',
	'seeking',
	'stalled',
	'suspend',
	'timeupdate',
	'toggle',
	'volumechange',
	'waiting',
	'waitingforkey',
];

/** Window-own events the document never receives: focus and blur of the tab, its load, size and errors. */
const DOCUMENT_UNREACHED_EVENTS = ['blur', 'error', 'focus', 'load', 'resize'];

/** Fired at the document without bubbling, so it stops there. */
const WINDOW_UNREACHED_EVENTS = ['selectionchange'];

function eventMapKeys(mapName: string): string[] {
	const fileName = '/markless-global-events.ts';
	const text = `type Keys = keyof ${mapName};`;
	const host = ts.createCompilerHost({ lib: ['lib.dom.d.ts', 'lib.es2022.d.ts'], noEmit: true });
	const readFile = host.getSourceFile.bind(host);
	host.getSourceFile = (name, languageVersion) =>
		name === fileName
			? ts.createSourceFile(fileName, text, languageVersion)
			: readFile(name, languageVersion);
	const program = ts.createProgram(
		[fileName],
		{ lib: ['lib.dom.d.ts', 'lib.es2022.d.ts'], noEmit: true, types: [] },
		host,
	);
	const checker = program.getTypeChecker();
	const alias = program.getSourceFile(fileName)!.statements[0] as ts.TypeAliasDeclaration;
	const keys = checker.getTypeFromTypeNode(alias.type);
	const members = keys.isUnion() ? keys.types : [keys];
	const names = members
		.filter((member): member is ts.StringLiteralType => member.isStringLiteral())
		.map((member) => member.value);
	if (names.length < 50) throw new Error(`${mapName} resolved to ${names.length} keys; lib.dom did not load.`);
	return names;
}

// The compiler lowercases the name after the prefix, so a mixed-case type (DOMContentLoaded) cannot be spelled; webkit aliases fire as their standard names.
function reachable(names: string[], unreached: ReadonlyArray<string>): string[] {
	const refused = new Set(unreached);
	return [...new Set(names)]
		.filter(
			(name) => name === name.toLowerCase() && !name.startsWith('webkit') && !refused.has(name),
		)
		.sort();
}

export function generateGlobalEventTypes(): { readonly dts: string; readonly compiler: string } {
	const documentTypes = reachable(eventMapKeys('DocumentEventMap'), [
		...ELEMENT_ONLY_EVENTS,
		...DOCUMENT_UNREACHED_EVENTS,
	]);
	const windowTypes = reachable(eventMapKeys('WindowEventMap'), [
		...ELEMENT_ONLY_EVENTS,
		...WINDOW_UNREACHED_EVENTS,
	]);
	const header = [
		'// Generated by packages/typescript-plugin/scripts/generate-global-event-types.ts from',
		"// TypeScript's DocumentEventMap and WindowEventMap; do not edit.",
	].join('\n');
	const union = (names: string[]) => names.map((name) => `'${name}'`).join(' | ');
	const dts = `${header}
declare namespace __MarklessTypeService {
	/** The DOM events an element may listen for on the document: \`onDocumentKeyDown\`. */
	type DocumentEventType = ${union(documentTypes)};
	/** The DOM events an element may listen for on the window: \`onWindowResize\`. */
	type WindowEventType = ${union(windowTypes)};
}
`;
	const compiler = `${header}
export const DOCUMENT_EVENT_TYPES: ReadonlySet<string> = new Set('${documentTypes.join(' ')}'.split(' '));
export const WINDOW_EVENT_TYPES: ReadonlySet<string> = new Set('${windowTypes.join(' ')}'.split(' '));
`;
	return { dts, compiler };
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const { dts, compiler } = generateGlobalEventTypes();
	writeFileSync(GLOBAL_EVENT_TYPES_DTS_FILE, dts);
	writeFileSync(GLOBAL_EVENT_TYPES_COMPILER_FILE, compiler);
}
