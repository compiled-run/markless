import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const { url } = JSON.parse(readFileSync('/tmp/jev-advanced/server.json'));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
page.setDefaultTimeout(10000);
const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push({type:r.resourceType(),url:r.url()}));
await page.goto(url);
console.log('home',await page.locator('main').textContent());
await page.evaluate(()=>window.experimentDocument='same');
await page.getByTestId('count').click();
await page.waitForFunction(()=>document.querySelector('[data-testid="count"]').textContent==='1');
await page.getByTestId('nav-workspace').click();
await page.locator('[data-page="workspace"]').waitFor();
await page.getByTestId('outer-trigger').click();
await page.waitForFunction(()=>document.activeElement?.getAttribute('data-testid')==='outer-content');
await page.getByTestId('combo-input').fill('a');
await page.waitForTimeout(200);
console.log('combo',await page.getByTestId('combo-input').getAttribute('aria-expanded'),await page.locator('[data-option]').allTextContents());
await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
await page.waitForTimeout(200);
console.log('selected',await page.getByTestId('selected').textContent());
await page.getByTestId('inner-trigger').click();
await page.waitForFunction(()=>document.activeElement?.getAttribute('data-testid')==='inner-content');
await page.keyboard.press('Escape');
await page.waitForTimeout(200);
console.log('escape',await page.getByTestId('outer-backdrop').isVisible(),await page.getByTestId('inner-backdrop').isVisible());
await page.getByTestId('outer-close').click();
await page.getByTestId('nav-todos').click();
await page.locator('.new-todo').fill('Probe');await page.locator('.new-todo').press('Enter');
await page.waitForTimeout(200);
console.log('todos',await page.locator('.todo-list').textContent(),'sameDocument',await page.evaluate(()=>window.experimentDocument));
await page.goBack();await page.locator('[data-page="workspace"]').waitFor();
console.log('back',await page.locator('main').getAttribute('data-page'));
writeFileSync('/tmp/jev-advanced/preflight.json',JSON.stringify({errors,requests},null,2));
console.log('errors',errors);
await browser.close();
