/** Runtime codes a reader can cause, though they have no written guide yet. */
const READER_RUNTIME = new Set(['SHARED_SHAPE_MISMATCH', 'ELEMENT_HANDLE_INSTANCE_AMBIGUOUS', 'COMPONENT_PART_AS_PAGE', 'ROW_COMPONENT_INTERACTIVE', 'PROJECTION_NOT_RENDERED']);

/**
 * A code's area. A matching prefix decides it, except that a code raised while a page runs is an internal
 * check unless it belongs to the router, has a written guide, or is one a reader can cause. A code no prefix
 * names is Markless checking its own build, so it is internal too.
 */
export function areaOf(code: string, stage: 'compile' | 'build' | 'runtime', guided: boolean): ErrorArea {
	const bare = code.replace(/^MARKLESS_/, '');
	let best: readonly [string, ErrorArea] | undefined;
	for (const entry of PREFIXES) if (bare.startsWith(entry[0]) && (!best || entry[0].length > best[0].length)) best = entry;
	if (!best) return guided ? 'build' : 'internal';
	const area = best[1];
	if (stage !== 'runtime' || guided || area === 'router' || READER_RUNTIME.has(bare)) return area;
	return 'internal';
}

