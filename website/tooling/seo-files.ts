// Emits robots.txt, sitemap.xml and llms.txt from nav.ts into the build output, so a build never rewrites a tracked file.
import { readFileSync } from 'node:fs';
import type { Plugin } from 'vite';
import { flatNav, nav, siteDescription, siteName, siteOrigin } from '../nav.ts';

const corePackage = new URL('../../packages/core/package.json', import.meta.url);

/** XML has five characters that cannot be written as themselves. */
const xmlText = (text: string) =>
	text
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&apos;');

const absolute = (href: string) => `${siteOrigin}${href}`;

/** The three files an agent or a crawler reads before any page, by file name. */
export function seoFileContents(version: string): Record<string, string> {
	const robots = `# ${siteName} docs, served at ${siteOrigin}.
# Generated by website/tooling/seo-files.ts from nav.ts.
User-agent: *
Allow: /

Sitemap: ${siteOrigin}/sitemap.xml
`;

	const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by website/tooling/seo-files.ts from nav.ts. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${flatNav
	.map(
		(entry) =>
			`\t<url>\n\t\t<loc>${xmlText(absolute(entry.href))}</loc>\n\t\t<changefreq>weekly</changefreq>\n\t</url>`,
	)
	.join('\n')}
</urlset>
`;

	const llms = `# ${siteName} docs

> ${siteDescription}

Generated by website/tooling/seo-files.ts from nav.ts. Every page below is prose plus
runnable ${'`.tsrx`'} files, written against @markless/* ${version}. Where something
on this site does not work on that version, the page says so out loud in a callout
rather than documenting the plan.

${nav
	.map(
		(section) =>
			`## ${section.title}\n\n${section.entries
				.map((entry) => `- [${entry.title}](${absolute(entry.href)}): ${entry.description ?? ''}`)
				.join('\n')}`,
	)
	.join('\n\n')}
`;

	return { 'robots.txt': robots, 'sitemap.xml': sitemap, 'llms.txt': llms };
}

function currentFiles() {
	const { version } = JSON.parse(readFileSync(corePackage, 'utf8')) as { version: string };
	return seoFileContents(version);
}

const CONTENT_TYPES: Readonly<Record<string, string>> = {
	'robots.txt': 'text/plain; charset=utf-8',
	'sitemap.xml': 'application/xml; charset=utf-8',
	'llms.txt': 'text/plain; charset=utf-8',
};

export function seoFiles(): Plugin {
	let base = '/';
	return {
		name: 'compiled-website:seo-files',
		// Ahead of the router, whose dev middleware answers every other path.
		enforce: 'pre',
		configResolved(config) {
			base = config.base;
		},
		configureServer(server) {
			server.middlewares.use((req, res, next) => {
				const path = (req.url ?? '').split('?', 1)[0]!;
				const name = path.startsWith(base) ? path.slice(base.length) : '';
				const type = Object.hasOwn(CONTENT_TYPES, name) ? CONTENT_TYPES[name] : undefined;
				if (!type) return next();
				res.setHeader('content-type', type);
				res.end(currentFiles()[name]);
			});
		},
		generateBundle() {
			if (this.environment?.config.consumer !== 'client') return;
			for (const [fileName, source] of Object.entries(currentFiles()))
				this.emitFile({ type: 'asset', fileName, source });
		},
	};
}
